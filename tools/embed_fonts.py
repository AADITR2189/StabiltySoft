#!/usr/bin/env python3
"""Embed the subset DejaVu fonts (src/report/fonts/*.ttf) as base64 in a TS module for jsPDF (works offline)."""
import base64, pathlib
d = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'report' / 'fonts'
out = ['// Generated by tools/embed_fonts.py from DejaVu Sans (subset). License: LICENSE-DejaVu.txt', '']
for name, var in [('DejaVuSans.ttf', 'DEJAVU_REGULAR'), ('DejaVuSans-Bold.ttf', 'DEJAVU_BOLD')]:
    out.append(f"export const {var} = '{base64.b64encode((d / name).read_bytes()).decode()}';")
(d / 'dejavu.ts').write_text('\n'.join(out) + '\n')
print('written', (d / 'dejavu.ts').stat().st_size, 'bytes')
